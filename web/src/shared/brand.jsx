// Each logo needs its own gradient id: when a shared one belongs to a hidden SVG,
// some engines leave the other unpainted.
let next = 0
const gradientId = () => `vs-ember-${(next += 1)}`

function Ember({ id, x1 = '0', y1 = '0', x2 = '1', y2 = '1' }) {
  return (
    <linearGradient id={id} x1={x1} y1={y1} x2={x2} y2={y2}>
      <stop offset="0" stopColor={EMBER[0]} />
      <stop offset="0.5" stopColor={EMBER[1]} />
      <stop offset="1" stopColor={EMBER[2]} />
    </linearGradient>
  )
}

/** The V. `size` is its height in pixels. */
export function VMark({ size = 32, className }) {
  const id = gradientId()
  return (
    <svg className={className} width={Math.round((size * 1600) / 1466)} height={size}
      viewBox="0 0 1600 1466" aria-hidden="true">
      <defs><Ember id={id} /></defs>
      <polygon points={V_POINTS} fill={`url(#${id})`} />
    </svg>
  )
}

/** VIBESTREAM. `size` is its cap height in pixels. */
export function Wordmark({ size = 24, className }) {
  const id = gradientId()
  const [, , width, height] = WORDMARK_BOX.split(' ').map(Number)
  return (
    <svg className={className} width={Math.round((size * width) / height)} height={size}
      viewBox={WORDMARK_BOX} aria-label="VibeStream" role="img">
      <defs><Ember id={id} x1="0" y1="0" x2="1" y2="0.6" /></defs>
      <path d={WORDMARK_PATH} fill={`url(#${id})`} />
    </svg>
  )
}
