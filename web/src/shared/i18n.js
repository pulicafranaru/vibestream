// English is the key: t('Continue Watching') falls back to the English text.
// Plurals use tp(one, other, n); Romanian adds a third form ("20 de sezoane").

let language = 'en'
const listeners = new Set()

export const LANGUAGES = [
  { id: 'en', name: 'English' },
  { id: 'de', name: 'Deutsch' },
  { id: 'ro', name: 'Română' },
]

export function setLanguage(next) {
  const value = LANGUAGES.some((l) => l.id === next) ? next : 'en'
  if (value === language) return
  language = value
  listeners.forEach((fn) => fn(value))
}

export function getLanguage() {
  return language
}

export function onLanguage(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

const fill = (text, vars) =>
  vars ? text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m)) : text

export function t(english, vars) {
  const table = language === 'en' ? null : DICT[language]
  const found = table && table[english]
  return fill(typeof found === 'string' ? found : english, vars)
}

export function tp(one, other, n) {
  const vars = { n }
  if (language === 'en') return fill(n === 1 ? one : other, vars)
  const forms = DICT[language][`${one}|${other}`]
  if (!forms) return fill(n === 1 ? one : other, vars)
  if (language === 'ro') {
    const rest = n % 100
    const form = n === 1 ? forms[0] : n === 0 || (rest >= 1 && rest <= 19) ? forms[1] : forms[2]
    return fill(form, vars)
  }
  return fill(n === 1 ? forms[0] : forms[1], vars)
}

export function genreName(name) {
  const table = language === 'en' ? null : GENRES[language]
  return (table && table[name]) || name
}

export function rowTitle(row) {
  if (!row) return ''
  if (row.id && row.id.indexOf('genre-') === 0) return genreName(row.title)
  return t(row.title)
}

export function shortDate(value) {
  const date = value instanceof Date ? value : new Date(value)
  const locale = { en: 'en-GB', de: 'de-DE', ro: 'ro-RO' }[language]
  try {
    return date.toLocaleDateString(locale, { day: 'numeric', month: 'short' })
  } catch {
    return date.toDateString()
  }
}

